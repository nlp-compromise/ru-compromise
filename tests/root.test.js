import test from 'tape'
import nlp from './_lib.js'
const here = '[root-match] '
nlp.verbose(false)

test('root-match:', function (t) {
  const arr = [
    // verb toRoots
    ["побриться", "{побриться}"],//same
    ["побреюсь", "{побриться}"],
    ["побреешься", "{побриться}"],
    ["побреется", "{побриться}"],
    ["побреемся", "{побриться}"],
    ["побреетесь", "{побриться}"],
    ["побреются", "{побриться}"],

    ["выучиваю", "{выучивать}"],
    ["выучиваешь", "{выучивать}"],
    ["выучивает", "{выучивать}"],
    ["выучиваем", "{выучивать}"],
    ["выучиваете", "{выучивать}"],
    ["выучивают", "{выучивать}"],

    ["выучу", "{выучить}"],
    ["выучишь", "{выучить}"],
    ["выучит", "{выучить}"],
    ["выучим", "{выучить}"],
    ["выучите", "{выучить}"],
    ["выучат", "{выучить}"],

    // past-tense forms
    ["говорила", "{говорить}"],
    ["сказали", "{сказать}"],
    ["вернулась", "{вернуться}"],
    ["шёл", "{идти}"],
    ["пошла", "{пойти}"],

    // imperative forms
    ["читайте", "{читать}"],
    ["помогите", "{помочь}"],

    // he runs
    ['я	бегу́', '#Pronoun {бежать}'],
    ['ты бежи́шь', '#Pronoun {бежать}'],
    ['она	бежи́т', '#Pronoun {бежать}'],
    ['мы бежи́м', '#Pronoun {бежать}'],
    ['вы	бежи́те', '#Pronoun {бежать}'],
    ['они	бегу', '#Pronoun {бежать}'],
    ['он бежит в школу', '#Pronoun {бежать} в #Noun']

  ]
  arr.forEach(function (a) {
    const [str, match] = a
    const doc = nlp(str).compute('root')
    const tags = doc.json()[0].terms.map(term => term.tags[0])
    const msg = `'${(str + "' ").padEnd(20, ' ')}  - '${tags.join(', ')}'`
    t.equal(doc.has(match), true, here + msg)
  })
  t.end()
})
