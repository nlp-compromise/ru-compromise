import test from 'tape'
import nlp from '../../_lib.js'
const here = '[ru-sentences] '
nlp.verbose(false)

test('sentences:', function (t) {
  const arr = [
    // terminators
    ['Я поехал в Москву. Потом вернулся.', ['Я поехал в Москву.', 'Потом вернулся.']],
    ['Как дела? Очень хорошо! Спасибо.', ['Как дела?', 'Очень хорошо!', 'Спасибо.']],
    ['Который час? Три часа. Спасибо!', ['Который час?', 'Три часа.', 'Спасибо!']],
    ['Правда?! Не верю.', ['Правда?!', 'Не верю.']],
    ['Как красиво!!! Правда??', ['Как красиво!!!', 'Правда??']],
    ['Почему? Почему нет!', ['Почему?', 'Почему нет!']],
    ['Один. Два. Три.', ['Один.', 'Два.', 'Три.']],
    ['Да. Нет. Может быть.', ['Да.', 'Нет.', 'Может быть.']],
    ['Всё хорошо. Ещё не всё.', ['Всё хорошо.', 'Ещё не всё.']],
    ['Я думаю, что да. А ты?', ['Я думаю, что да.', 'А ты?']],
    ['Ой! Как больно...', ['Ой!', 'Как больно...']],
    ['Он живёт в Санкт-Петербурге. Она тоже.', ['Он живёт в Санкт-Петербурге.', 'Она тоже.']],
    // not terminators
    ['Я люблю кофе', ['Я люблю кофе']],
    ['Я видел Марка, Луку и Анну.', ['Я видел Марка, Луку и Анну.']],
    ['город красивый; море синее.', ['город красивый; море синее.']],
    ['Тише, мыши, кот на крыше.', ['Тише, мыши, кот на крыше.']],
    ['Он сказал: приду завтра.', ['Он сказал: приду завтра.']],
    // dashes
    ['Москва — столица России. Петербург больше?', ['Москва — столица России.', 'Петербург больше?']],
    ['— Привет, — сказал он. — Как дела?', ['— Привет, — сказал он.', '— Как дела?']],
    // ellipses
    ['Идёт дождь... сильный', ['Идёт дождь... сильный']],
    ['Хм... не знаю. Посмотрим.', ['Хм... не знаю.', 'Посмотрим.']],
    // quotations
    ['«Иди сюда!» — сказала Мария. Потом ушла.', ['«Иди сюда!» — сказала Мария.', 'Потом ушла.']],
    ['«Привет!» — сказал он.', ['«Привет!» — сказал он.']],
    ['Он сказал: «Не знаю». Потом ушёл.', ['Он сказал: «Не знаю».', 'Потом ушёл.']],
    ['«Куда идёшь?» — спросил Лука. «Домой».', ['«Куда идёшь?» — спросил Лука.', '«Домой».']],
    // abbreviations
    // 'т.д.' is an abbreviation, so it never ends a sentence (like 'etc.' in english)
    ['Он купил хлеб, молоко и т.д. Потом вернулся домой.', ['Он купил хлеб, молоко и т.д. Потом вернулся домой.']],
    ['Хлеб, молоко и т.д. лежат на столе.', ['Хлеб, молоко и т.д. лежат на столе.']],
    ['Это было в 1945 г.', ['Это было в 1945 г.']],
    ['Г-н Иванов пришёл.', ['Г-н Иванов пришёл.']],
    // numbers
    ['Стоит 3,50 рубля. Я куплю.', ['Стоит 3,50 рубля.', 'Я куплю.']],
    ['Стоит 3.50 рубля. Хорошо.', ['Стоит 3.50 рубля.', 'Хорошо.']],
    ['Стоит 1 000 рублей в месяц.', ['Стоит 1 000 рублей в месяц.']],
    ['Он пришёл в 8.30. Мы ушли.', ['Он пришёл в 8.30.', 'Мы ушли.']],
    ['Он родился в 1990 году. Живёт в Москве.', ['Он родился в 1990 году.', 'Живёт в Москве.']],
    ['Мне 10. Ему 12.', ['Мне 10.', 'Ему 12.']],
    ['Версия 2.0.1 вышла. Скачай её!', ['Версия 2.0.1 вышла.', 'Скачай её!']],
    // urls + emails
    ['www.primer.ru это сайт. Посети его.', ['www.primer.ru это сайт.', 'Посети его.']],
    ['Напиши на maria@primer.ru сегодня. Спасибо.', ['Напиши на maria@primer.ru сегодня.', 'Спасибо.']],
    // newlines
    ['Привет!\n\nКак дела?', ['Привет!', 'Как дела?']],
    ['Список покупок\nХлеб и молоко', ['Список покупок', 'Хлеб и молоко']],
    // extra whitespace
    ['Привет   мир.  Как  дела?', ['Привет   мир.', 'Как  дела?']],
    // uppercase
    ['ПРИВЕТ. КАК ДЕЛА?', ['ПРИВЕТ.', 'КАК ДЕЛА?']],
  ]
  arr.forEach(a => {
    const [str, want] = a
    const doc = nlp(str)
    t.deepEqual(doc.fullSentences().out('array'), want, here + JSON.stringify(str))
    t.equal(doc.text(), str, here + 'roundtrip ' + JSON.stringify(str))
  })
  t.end()
})

test('sentence api:', function (t) {
  const doc = nlp('Я поехал в Москву. Потом вернулся? Да!')
  t.equal(doc.length, 3, here + 'doc length')
  t.equal(doc.eq(1).text(), 'Потом вернулся?', here + 'eq(1)')
  t.equal(doc.first().text(), 'Я поехал в Москву.', here + 'first()')
  t.equal(doc.last().text(), 'Да!', here + 'last()')
  t.equal(doc.match('вернулся').fullSentences().text(), 'Потом вернулся?', here + 'fullSentences() of a match')
  t.equal(doc.if('москву').length, 1, here + 'if()')
  t.equal(doc.ifNo('москву').length, 2, here + 'ifNo()')
  t.deepEqual(doc.json().map(o => o.text), ['Я поехал в Москву.', 'Потом вернулся?', 'Да!'], here + 'json text')
  t.end()
})
