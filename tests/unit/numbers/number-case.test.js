test('number-case-kept:', function (t) {
  const list = [
    ['пяти книг', 1, 'шести книг'],
    ['к пяти часам', 2, 'к семи часам'],
    ['с пятью друзьями', 1, 'с шестью друзьями'],
    ['от двадцати девяти', 1, 'от тридцати'],
    ['около девяноста девяти', 1, 'около ста'],
    ['двух тысяч', 1000, 'трёх тысяч'],
    ['двумя тысячами', 3000, 'пятью тысячами'],
    ['с тремя', 1, 'с четырьмя'],
    ['о четырёх', 1, 'о пяти'],
    ['одна', 1, 'две'],
    ['двадцать одну', 1, 'двадцать две'],
    ['двадцать одна', 10, 'тридцать одна'],
    ['пятого мая', 1, 'шестого мая'],
    ['в двадцать первом веке', 1, 'в двадцать втором веке'],
    ['первая глава', 2, 'третья глава'],
    ['вторую главу', 1, 'третью главу'],
    ['девятнадцатому', 1, 'двадцатому'],
  ]
  list.forEach(a => {
    const [str, n, want] = a
    const doc = nlp(str)
    doc.numbers().add(n)
    t.equal(doc.text(), want, here + str + ' + ' + n)
  })
  let doc = nlp('с пятью друзьями')
  doc.numbers().set(40)
  t.equal(doc.text(), 'с сорока друзьями', here + 'set keeps case')
  doc = nlp('без пяти')
  doc.numbers().set(1234)
  t.equal(doc.text(), 'без тысячи двухсот тридцати четырёх', here + 'set keeps genitive')
  t.end()
})
