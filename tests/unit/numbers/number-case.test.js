const names = ['nominative', 'genitive', 'dative', 'accusative', 'instrumental', 'prepositional']

test('number-case-parse:', function (t) {
  arr.forEach(a => {
    a.slice(1).forEach(str => {
      let num = a[0]
      // on its own, 'семью' is 'the family'
      if (str === 'семью') {
        str = 'двадцатью семью'
        num = 27
      }
      const nums = nlp(str).numbers()
      t.equal(nums.length, 1, here + 'one number: ' + str)
      t.equal(nums.get()[0], num, here + 'parse: ' + str)
    })
  })
  t.end()
})

test('number-decline:', function (t) {
  arr.forEach(a => {
    const res = nlp(a[1]).numbers().decline()[0]
    names.forEach((name, i) => {
      t.equal(res[name], a[i + 1], here + name + ': ' + a[1])
    })
  })
  // from digits, too
  let res = nlp('25').numbers().decline()[0]
  t.equal(res.instrumental, 'двадцатью пятью', here + 'decline digits')
  // gender is kept
  res = nlp('двадцать одна').numbers().decline()[0]
  t.equal(res.nominative, 'двадцать одна', here + 'feminine nominative')
  t.equal(res.accusative, 'двадцать одну', here + 'feminine accusative')
  t.equal(res.instrumental, 'двадцатью одной', here + 'feminine instrumental')
  res = nlp('две').numbers().decline()[0]
  t.equal(res.nominative, 'две', here + 'две nominative')
  t.equal(res.genitive, 'двух', here + 'две genitive')
  // ordinals
  res = nlp('пятый').numbers().decline()[0]
  t.deepEqual(res, {
    nominative: 'пятый',
    genitive: 'пятого',
    dative: 'пятому',
    accusative: 'пятый',
    instrumental: 'пятым',
    prepositional: 'пятом',
  }, here + 'ordinal')
  res = nlp('двадцать первая').numbers().decline()[0]
  t.equal(res.accusative, 'двадцать первую', here + 'feminine ordinal')
  res = nlp('5-й').numbers().decline()[0]
  t.equal(res.genitive, 'пятого', here + 'numeric ordinal')
  // nth
  t.equal(nlp('пять и шесть').numbers().decline(1)[0].genitive, 'шести', here + 'decline(n)')
  t.deepEqual(nlp('кот').numbers().decline(), [], here + 'decline nothing')
  // no words for these
  t.deepEqual(nlp('3,5').numbers().decline(), [null], here + 'decline decimal')
  t.end()
})

