test('number-parse:', function (t) {
  arr.forEach(a => {
    const [num, str] = a
    const doc = nlp(str)
    t.equal(doc.numbers().length, 1, here + 'one number: ' + str)
    t.equal(doc.numbers().get()[0], num, here + 'parse: ' + str)
  })
  t.end()
})

test('number-to-text:', function (t) {
  arr.forEach(a => {
    const [num, str] = a
    const doc = nlp(String(num))
    doc.numbers().toText()
    t.equal(doc.text(), str, here + 'toText: ' + num)
  })
  t.end()
})

test('number-to-number:', function (t) {
  arr.forEach(a => {
    const [num, str] = a
    const doc = nlp(str)
    doc.numbers().toNumber()
    t.equal(doc.text(), String(num), here + 'toNumber: ' + str)
  })
  t.end()
})

test('number-round-trip:', function (t) {
  // text → digits → text, for a spread of numbers
  for (let n = 0; n < 3000; n += 7) {
    const doc = nlp(String(n))
    doc.numbers().toText()
    const str = doc.text()
    doc.numbers().toNumber()
    if (doc.text() !== String(n)) {
      t.fail(here + 'round-trip ' + n + ' → ' + str + ' → ' + doc.text())
    }
  }
  const big = [10203, 99999, 100001, 123456, 700700, 1000100, 20000002, 999999999, 1000000001, 123456789012, 999999999999999]
  big.forEach(n => {
    const doc = nlp(String(n))
    doc.numbers().toText()
    t.equal(doc.numbers().length, 1, here + 'one number: ' + n)
    t.equal(doc.numbers().get()[0], n, here + 'round-trip ' + n)
  })
  t.end()
})

