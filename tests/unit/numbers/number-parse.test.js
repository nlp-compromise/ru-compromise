test('number-negative:', function (t) {
  t.deepEqual(nlp('минус пять').numbers().get(), [-5], here + 'минус пять')
  t.deepEqual(nlp('минус двадцать пять градусов').numbers().get(), [-25], here + 'минус двадцать пять')
  t.equal(nlp('было минус пять градусов').numbers().text(), 'минус пять', here + 'sign is included')
  // a subtraction is two numbers
  t.deepEqual(nlp('десять минус пять').numbers().get(), [10, 5], here + 'subtraction')
  t.deepEqual(nlp('минус').numbers().get(), [], here + 'only a sign')

  let doc = nlp('было минус пять градусов')
  doc.numbers().toNumber()
  t.equal(doc.text(), 'было -5 градусов', here + 'toNumber negative')
  doc.numbers().toText()
  t.equal(doc.text(), 'было минус пять градусов', here + 'toText negative')

  doc = nlp('-25')
  doc.numbers().toText()
  t.equal(doc.text(), 'минус двадцать пять', here + 'toText -25')
  t.end()
})
