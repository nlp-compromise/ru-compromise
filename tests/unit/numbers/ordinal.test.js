test('ordinal-parse:', function (t) {
  arr.forEach(a => {
    const [num, , ord] = a
    const nums = nlp(ord).numbers()
    t.equal(nums.length, 1, here + 'one number: ' + ord)
    t.equal(nums.get()[0], num, here + 'parse: ' + ord)
    t.equal(nums.isOrdinal().found, true, here + 'isOrdinal: ' + ord)
    t.equal(nums.parse()[0].isOrdinal, true, here + 'parse().isOrdinal: ' + ord)
  })
  t.end()
})

test('to-ordinal:', function (t) {
  arr.forEach(a => {
    const [, card, ord] = a
    const doc = nlp(card)
    doc.numbers().toOrdinal()
    t.equal(doc.text(), ord, here + 'toOrdinal: ' + card)
    t.equal(doc.has('#Ordinal'), true, here + 'tagged: ' + ord)
  })
  t.end()
})

test('to-cardinal:', function (t) {
  arr.forEach(a => {
    const [, card, ord] = a
    const doc = nlp(ord)
    doc.numbers().toCardinal()
    t.equal(doc.text(), card, here + 'toCardinal: ' + ord)
    t.equal(doc.has('#Ordinal'), false, here + 'un-tagged: ' + card)
  })
  t.end()
})

test('ordinal-digits:', function (t) {
  arr.forEach(a => {
    const [num, , ord] = a
    // text → digits
    let doc = nlp(ord)
    doc.numbers().toNumber()
    t.equal(doc.text(), num + '-й', here + 'toNumber: ' + ord)
    // digits → text
    doc = nlp(num + '-й')
    doc.numbers().toText()
    t.equal(doc.text(), ord, here + 'toText: ' + num + '-й')
  })
  t.end()
})

