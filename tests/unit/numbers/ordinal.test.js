test('ordinal-agreement:', function (t) {
  // cardinal → ordinal keeps the case, and the gender
  const list = [
    ['пять', 'пятый'],
    ['пяти', 'пятого'],
    ['пятью', 'пятым'],
    ['одна', 'первая'],
    ['одну', 'первую'],
    ['одно', 'первое'],
    ['двадцать одна', 'двадцать первая'],
    ['двух', 'второго'],
    ['трём', 'третьему'],
  ]
  list.forEach(a => {
    const doc = nlp(a[0])
    doc.numbers().toOrdinal()
    t.equal(doc.text(), a[1], here + 'toOrdinal: ' + a[0])
  })
  // .. and so does ordinal → cardinal
  const back = [
    ['пятого', 'пяти'],
    ['пятому', 'пяти'],
    ['пятым', 'пятью'],
    ['первая', 'одна'],
    ['первую', 'одну'],
    ['первое', 'одно'],
    ['вторая', 'две'],
    ['двадцать первую', 'двадцать одну'],
    ['сорокового', 'сорока'],
    ['третьими', 'тремя'],
  ]
  back.forEach(a => {
    const doc = nlp(a[0])
    doc.numbers().toCardinal()
    t.equal(doc.text(), a[1], here + 'toCardinal: ' + a[0])
  })
  t.end()
})

test('ordinal-sentences:', function (t) {
  let doc = nlp('он живёт на пятом этаже')
  t.deepEqual(doc.numbers().get(), [5], here + 'пятом')
  doc.numbers().toNumber()
  t.equal(doc.text(), 'он живёт на 5-м этаже', here + 'на 5-м этаже')

  doc = nlp('в две тысячи двадцать шестом году')
  t.equal(doc.numbers().length, 1, here + 'year is one number')
  t.deepEqual(doc.numbers().get(), [2026], here + 'year')
  doc.numbers().toNumber()
  t.equal(doc.text(), 'в 2026-м году', here + 'year toNumber')

  doc = nlp('пятого мая две тысячи двадцатого года')
  t.deepEqual(doc.numbers().get(), [5, 2020], here + 'date')

  doc = nlp('в девяностых годах')
  t.deepEqual(doc.numbers().get(), [90], here + 'девяностых')

  doc = nlp('это его 3-я книга')
  doc.numbers().toText()
  t.equal(doc.text(), 'это его третья книга', here + '3-я книга')

  // an ordinal ends its number
  doc = nlp('двадцать пятый шестой')
  t.deepEqual(doc.numbers().get(), [25, 6], here + 'two ordinals')

  // digits
  doc = nlp('5 книг')
  doc.numbers().toOrdinal()
  t.equal(doc.text(), '5-й книг', here + 'digits toOrdinal')
  doc.numbers().toCardinal()
  t.equal(doc.text(), '5 книг', here + 'digits toCardinal')

  // not a number
  t.equal(nlp('многотысячный митинг').numbers().found, false, here + 'многотысячный')
  t.equal(nlp('многомиллионный город').numbers().found, false, here + 'многомиллионный')
  t.end()
})
